'use client';

// A quiet "which AI wrote this" badge shown under every finished assistant
// reply: a provider-coloured mark + the model's display label. The chain step
// that answered (e.g. "Groq · key 2") and the fallback count live in the
// tooltip; when earlier providers failed, "after N fallbacks" is also shown
// inline so a degraded answer is never mistaken for the primary model.

import type { GeneratedBy } from '@/shared/types';

// Provider accents. Light/dark pairs keep the dot + ring legible on both the
// cream canvas and the dark theme (dark: follows html[data-theme], globals.css).
const PROVIDER: Record<
  GeneratedBy['provider'],
  { name: string; dot: string; ring: string }
> = {
  anthropic: {
    name: 'Anthropic',
    dot: 'bg-[#d97757] dark:bg-[#e58a6c]',
    ring: 'ring-[#d97757]/25 dark:ring-[#e58a6c]/30',
  },
  groq: {
    name: 'Groq',
    dot: 'bg-[#f55036] dark:bg-[#ff6a52]',
    ring: 'ring-[#f55036]/25 dark:ring-[#ff6a52]/30',
  },
  gemini: {
    name: 'Google Gemini',
    dot: 'bg-[#4285f4] dark:bg-[#7aa7ff]',
    ring: 'ring-[#4285f4]/25 dark:ring-[#7aa7ff]/30',
  },
};

function plural(n: number, word: string): string {
  return `${n} ${word}${n === 1 ? '' : 's'}`;
}

export function ModelBadge({ info }: { info: GeneratedBy }) {
  const p = PROVIDER[info.provider] ?? {
    name: info.provider,
    dot: 'bg-muted-soft',
    ring: 'ring-hairline',
  };
  const fallbacks = Math.max(0, info.fallbacks || 0);
  const tooltip = [
    `Generated by ${info.label} (${p.name})`,
    info.model && `Model: ${info.model}`,
    info.step && `Answered by: ${info.step}`,
    fallbacks > 0
      ? `After ${plural(fallbacks, 'fallback')} — earlier providers failed`
      : 'First choice — no fallbacks',
  ]
    .filter(Boolean)
    .join('\n');

  return (
    <span
      title={tooltip}
      aria-label={`Generated by ${info.label}${fallbacks > 0 ? `, after ${plural(fallbacks, 'fallback')}` : ''}`}
      className="inline-flex max-w-full items-center gap-1.5 rounded-full border border-hairline bg-surface-card/50 px-2 py-0.5 text-[11px] leading-none text-muted"
    >
      <span
        aria-hidden="true"
        className={`inline-block h-1.5 w-1.5 shrink-0 rounded-full ring-2 ${p.dot} ${p.ring}`}
      />
      <span className="truncate">{info.label}</span>
      {fallbacks > 0 && (
        <span className="shrink-0 text-amber-ink">
          · after {plural(fallbacks, 'fallback')}
        </span>
      )}
    </span>
  );
}

export default ModelBadge;
